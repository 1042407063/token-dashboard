# -*- coding: utf-8 -*-
"""开机自启：在用户启动文件夹放一个启动脚本。

为什么不用注册表 Run 键？本机安全策略把 reg.exe 与 WScript.Shell COM 都列了黑名单，
直接用文件方式最稳，而且不需要管理员权限、删文件即可撤销。

编码说明：启动脚本里含中文路径，必须按本机 ANSI 代码页（中文 Windows 为 cp936）写入，
cmd.exe 才能正确解析。用 Python 的 mbcs 编码，等价于系统当前 ANSI 代码页。

用法：
  python tools/autostart.py install
  python tools/autostart.py uninstall
  python tools/autostart.py status
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SERVER = os.path.join(ROOT, "server.py")

STARTUP = os.path.join(
    os.environ.get("APPDATA", os.path.expanduser("~")),
    "Microsoft", "Windows", "Start Menu", "Programs", "Startup")
ENTRY = os.path.join(STARTUP, "token-panel.cmd")


def pythonw():
    exe = sys.executable or "pythonw.exe"
    cand = os.path.join(os.path.dirname(exe), "pythonw.exe")
    return cand if os.path.exists(cand) else exe


def body():
    return (
        "@echo off\r\n"
        "rem WorkBuddy token panel - autostart entry, generated by tools/autostart.py\r\n"
        "start \"\" \"%s\" \"%s\"\r\n" % (pythonw(), SERVER)
    )


def install():
    if not os.path.exists(SERVER):
        print("找不到 server.py：%s" % SERVER)
        return 1
    os.makedirs(STARTUP, exist_ok=True)
    with open(ENTRY, "w", encoding="mbcs", errors="replace", newline="") as f:
        f.write(body())
    print("已写入启动项：%s" % ENTRY)
    print("目标：%s" % pythonw())
    print("脚本：%s" % SERVER)
    print("下次登录 Windows 时会自动在后台启动面板。")
    print("撤销：运行 uninstall-autostart.bat")
    return 0


def uninstall():
    if os.path.exists(ENTRY):
        os.remove(ENTRY)
        print("已删除启动项：%s" % ENTRY)
    else:
        print("没有找到启动项，无需处理。")
    return 0


def status():
    print("启动项路径：%s" % ENTRY)
    if os.path.exists(ENTRY):
        print("状态：已启用")
        try:
            with open(ENTRY, "r", encoding="mbcs", errors="replace") as f:
                for line in f:
                    if line.strip().startswith("start "):
                        print("内容：%s" % line.strip())
        except OSError as e:
            print("读取失败：%s" % e)
    else:
        print("状态：未启用")
    return 0


def main(argv):
    action = (argv[1] if len(argv) > 1 else "status").lower()
    if action == "install":
        return install()
    if action == "uninstall":
        return uninstall()
    if action == "status":
        return status()
    print("用法：python tools/autostart.py [install|uninstall|status]")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
